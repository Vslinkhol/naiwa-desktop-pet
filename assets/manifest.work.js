window.NAIWA_MANIFEST_WORK = {

  animations: {

    /**
     * 工作模式的静态待机图。
     *
     * ⚠️ 和 `ASSETS.md` 第 7 节的说法略有出入：那份文档建议共享素材声明写进
     * `assets/manifest.js`，但共享清单在结构改造后就冻结了，那样你会被卡住。
     * 所以约定成：**文件仍然放 `assets/shared/idle_work.png`**（那确实是共享目录），
     * 但**声明写在这里**——这是你名下的文件，随便改。
     *
     * 没提供就自动复用 idle_relax。但两张一样的话，用户切模式时视觉上毫无变化，
     * 建议还是做一张不同姿势的。
     *
     * 素材来源：工作区提供的 `assets/工作模式素材/工作模式待机.png`（1398x1198，白底）。
     * 处理方式：白底 + 柔和投影一起抠掉 → 裁到奶蛙 → 统一到 380x380 画布 →
     * 对齐锚点（脚底 y=348、水平中心 x=190，画布坐标）。
     * 成品实测：包围盒 x 59..320（宽 262）、y 44..348（高 305），中心 189.5，脚底 348。
     * 高度和 idle_relax / sweat 一样是 305，所以切模式、切状态时奶蛙不会跳位置、不会变大小。
     *
     * 处理脚本留在工作区的 `.assetwork/build-work.js`（和程序运行无关），复现命令见该文件头部。
     */
    idle_work: {
      kind: 'file',
      src: 'shared/idle_work.png',

      /**
       * 槽位级命中区覆盖（核心层已支持，见 core/assets.js 的 hitRegion）。
       *
       * 共享清单里那组 `hit` 是按 `idle_relax` 量的（宽 152px），而这张实测宽
       * **262px** —— 共用一组的话两侧各约 **27.5 CSS px**「看得见点不到」，
       * 点到那儿会穿透到桌面。
       *
       * 换算：rx = 262/2/380 = 0.34，ry = 305/2/380 = 0.40，
       *       中心 x = 189.5/380 = 0.50，y = 196/380 = 0.516
       *
       * ⚠️ 换素材后要重新量（`ffmpeg -vf "alphaextract,bbox"`）。
       *    rx/ry 调得比主体明显大会让窗口拦住桌面点击——宁可小一点：
       *    点不中边缘只是手感差，挡住桌面用户会直接卸载。
       */
      hit: { type: 'ellipse', x: 0.50, y: 0.516, rx: 0.34, ry: 0.40 },
    },

    /**
     * CPU 占用高时的状态图。
     *
     * ⚠️ **这是「另一张基础图」，不是叠加层。**
     *
     * 原本的设计是在待机图上叠一层透明汗滴，但拿不到合适的素材；工作区提供的
     * `assets/工作模式素材/工作模式cpu占用高.png` 本身就是**完整的角色图**
     * （一只蔫掉的奶蛙），所以改成更干净的做法：
     *
     *   CPU ≥ 75%  → 整个换成这张图（ctx.pet.playLoop('sweat')）
     *   CPU ≤ 62%  → 换回待机图（ctx.pet.stopLoop()）
     *
     * 所以它放在 `animations` 里而不是 `overlays` 里。
     * 静态图不需要 loop，也不需要 duration。
     *
     * 处理这张素材时注意三件事（已全部做完，见下面的实测数据）：
     *   1. **白底要抠掉**。来源是 alpha=255 的不透明图，直接用会在桌面上
     *      显示成一个白方块。
     *   2. **统一到 380x380 画布**，并和解压模式的待机图对齐到同一个锚点：
     *      脚底 y=348、水平中心 x=190。`assets/manifest.js` 里的 `hit`
     *      就是照这个尺寸量出来的，不对齐的话切模式会看到奶蛙跳位置。
     *   3. 对齐之后，想调命中区域就在**这个槽位里加 `hit`**
     *      （核心层支持按槽位覆盖，不用去碰共享的 `assets/manifest.js`）。
     *      下面两条已经按实测宽度加好了，取值方法见 idle_work 那条的注释。
     *
     * 素材来源：`assets/工作模式素材/工作模式cpu占用高.png`（931x1414，白底，一只蔫掉的奶蛙）。
     * 这张来源比解压模式那两张脏一些，除了白底还有两处**画面伪影**必须一起处理，
     * 否则会在桌面上留下彩边和黑条（`build-work.js` 里裁剪外框解决）：
     *   · 左右各有 1~2px 的暖色边缘列（x=0,1 和 x=930），内容是画面内容的高饱和畸变；
     *   · 底部 9 行（y>=1405）是横跨整个宽度的近黑横带。
     *
     * 成品实测：380x380 RGBA，包围盒 x 92..287（宽 196）、y 44..348（高 305），
     * 中心 189.5、脚底 348，61 KB；背景平均 alpha 从 255 降到 68（说明白底确实抠干净了）。
     *
     * 处理脚本：工作区的 `.assetwork/build-work.js`（和程序运行无关），复现命令见该文件头部。
     */
    sweat: {
      kind: 'file',
      src: 'work/sweat.png',

      /**
       * 槽位级命中区覆盖，理由同 idle_work。
       * 实测宽 **196px**（包围盒 x 92..287），rx = 196/2/380 = 0.26，
       * ry = 305/2/380 = 0.40，中心与 idle_relax 相同。
       */
      hit: { type: 'ellipse', x: 0.50, y: 0.516, rx: 0.26, ry: 0.40 },
    },
  },

  /**
   * 叠加特效。
   *
   * 保留这个能力（`ctx.pet.setOverlay`），但**当前方案里没有用到**：
   * 打盹已经取消，流汗改成了换基础图。留空即可。
   */
  overlays: {},

  /**
   * 音效。留空就用内置合成音效。
   *
   *   bubble: 'sfx/bubble.mp3',   // 面板弹出
   *   pop:    'sfx/pop.mp3',      // 面板收起 / 复制成功
   *   drip:   'sfx/drip.mp3',     // CPU 飙高切换状态图时
   *   done:   'sfx/done.mp3',     // 待办勾选完成
   */
  sounds: {},
};